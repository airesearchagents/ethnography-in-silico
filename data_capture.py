"""Structured capture of the TMT (top management team) inter-agent deliberation.

This file turns the raw events from a meeting of the simulated team of
agents (language models given a name, a role and instructions), called the
deliberation, into an ordered record that keeps who said what to whom.

The original `TMTSystemWithA2A._extract_text_from_events` collapses an
ADK (Agent Development Kit: Google's ready-made software for building
agents) event stream into a single string — useful for printing the CEO's
final answer, lossy for research. This module preserves the structure:
each utterance keeps its author, addressee, kind (text / tool call (a request to the
software to carry out an action) /
delegation), and ordering. The resulting `DeliberationLog` is one of
the three primary research data streams (alongside the per-role
strategic artefacts, meaning strategy documents, and the panel debriefing
transcript, in which the researcher agent questions the six roles together).

Design notes
------------
- Pydantic models (record templates, not language models; Pydantic is a Python tool
  that checks records against templates) so the log serialises (saves) cleanly to JSON (a plain-text
  format of named fields) for the
  reproducibility artefacts.
- `walk_events` is forgiving: ADK events have shifted shape across
  versions, and some non-Gemini providers (companies or services that supply
  models) via LiteLLM (software that reaches many providers' models in the same
  way) produce slightly
  different event objects. We extract what we can and tag the rest as
  `kind="other"` so nothing is silently dropped.
- The walker (the function that steps through the events) does NOT depend on
  `google.adk` at import time — it
  inspects attributes via duck-typing (checking what an object offers, not its
  exact type) so unit tests (small automatic checks of the code) can pass synthetic
  (made-up) event objects without importing the heavy SDK (software development kit:
  here ADK itself).
"""

from __future__ import annotations

from datetime import datetime
from typing import Any, Iterable, List, Literal, Optional

from pydantic import BaseModel, Field

try:
    from .rag.schemas import Citation
except (ImportError, ValueError):  # pragma: no cover  (script-style execution)
    from rag.schemas import Citation  # type: ignore[no-redef]

EventKind = Literal[
    "text",          # a role agent's narrative utterance
    "delegation",    # a call to another agent (A2A, agent-to-agent, or sub_agent)
    "tool_call",     # tool invocation
    "tool_result",   # tool result
    "other",         # anything the walker could not classify
]


class DeliberationEvent(BaseModel):
    """One observable event in the TMT deliberation."""

    index: int = Field(..., description="0-based position in the deliberation stream.")
    role: str = Field(..., description="Author role: e.g. 'CEO', 'CTO'. 'unknown' if not derivable.")
    addressed_to: Optional[str] = Field(
        None,
        description="If this is a delegation or directed message, the recipient role; otherwise None.",
    )
    kind: EventKind = Field("text", description="Classification of this event.")
    text: str = Field("", description="The textual content of the event.")
    timestamp: str = Field(
        default_factory=lambda: datetime.utcnow().isoformat(),
        description="ISO 8601 timestamp (UTC) when the event was captured.",
    )
    raw_type: str = Field(
        "",
        description=(
            "The Python type name of the underlying ADK event, for "
            "post-hoc debugging. Useful when a provider's event shape "
            "changes and the walker needs adjusting."
        ),
    )
    phase: Optional[str] = Field(
        None,
        description=(
            "Deliberation-phase tag used by orchestrator modes that "
            "have explicit structure (e.g. 'initial_position', "
            "'round_3', 'convergence'). None for events from the "
            "ceo_led mode where the ADK transfer flow is itself the "
            "structure."
        ),
    )
    citations: List[Citation] = Field(
        default_factory=list,
        description=(
            "Citations the role attached to this utterance via its "
            "AgentAction.citations field — copied through the "
            "TranscriptEntry to here so the persisted deliberation "
            "log carries which retrieved snippets backed the role's "
            "claim. Empty list for no-RAG runs (and for events "
            "generated by the legacy CEO_LED ADK walker, which does "
            "not capture citations)."
        ),
    )


class DeliberationLog(BaseModel):
    """The full structured record of one TMT deliberation."""

    company: str
    industry_context: str
    product_type: str
    started_at: str = Field(default_factory=lambda: datetime.utcnow().isoformat())
    finished_at: Optional[str] = None
    events: list[DeliberationEvent] = Field(default_factory=list)

    def append(self, event: DeliberationEvent) -> None:
        self.events.append(event)

    def as_plain_transcript(self) -> str:
        """Render as a plain-text transcript for prompts (texts sent to a model to get
        a reply) that need it.

        Used by the prompt of the observer agent (the researcher agent that
        summarises what it saw): a single readable block
        the model can scan to produce its field notes.
        """
        lines: list[str] = []
        for ev in self.events:
            who = ev.role
            if ev.addressed_to:
                who = f"{ev.role} → {ev.addressed_to}"
            tag = f"[{ev.kind}]" if ev.kind != "text" else ""
            lines.append(f"{who} {tag}: {ev.text}".rstrip())
        return "\n".join(lines)


# ---------------------------------------------------------------------------
# Event-stream walker
# ---------------------------------------------------------------------------

def _read_attr(obj: Any, name: str, default: Any = None) -> Any:  # noqa: ANN401
    """Safe attribute read for duck-typed ADK events."""
    return getattr(obj, name, default)


def _classify(event: Any) -> EventKind:
    """Best-effort classification of an ADK event."""
    type_name = type(event).__name__.lower()
    if "tool" in type_name and "result" in type_name:
        return "tool_result"
    if "tool" in type_name and ("call" in type_name or "request" in type_name):
        return "tool_call"
    if "transfer" in type_name or "delegation" in type_name or "subagent" in type_name:
        return "delegation"
    # ADK content events typically expose `.content.parts` (the text path).
    if hasattr(event, "content") and hasattr(_read_attr(event, "content"), "parts"):
        return "text"
    return "other"


def _extract_text(event: Any) -> str:
    """Extract textual content from any ADK-style event."""
    parts: list[str] = []
    content = _read_attr(event, "content")
    if content is not None and hasattr(content, "parts"):
        for part in content.parts or []:
            text = _read_attr(part, "text")
            if text:
                parts.append(text)
    # Fallback: some event types expose .text directly
    direct_text = _read_attr(event, "text")
    if direct_text and not parts:
        parts.append(direct_text)
    return "\n".join(parts).strip()


def _extract_role(event: Any) -> str:
    """Best-effort sender role for an ADK event.

    ADK events carry the author in a few different attributes depending
    on version. We probe in order of preference.
    """
    for attr in ("author", "agent_name", "role", "name"):
        val = _read_attr(event, attr)
        if isinstance(val, str) and val:
            return val
    # Content-level role (e.g. Gemini's `content.role`).
    content = _read_attr(event, "content")
    if content is not None:
        crole = _read_attr(content, "role")
        if isinstance(crole, str) and crole:
            return crole
    return "unknown"


def _extract_target(event: Any) -> Optional[str]:
    """If this event is a delegation / transfer, return the target role."""
    for attr in ("transfer_to_agent", "delegate_to", "target_agent", "addressed_to"):
        val = _read_attr(event, attr)
        if isinstance(val, str) and val:
            return val
    return None


def walk_events(
    events: Iterable[Any],
    *,
    company: str,
    industry_context: str,
    product_type: str,
) -> DeliberationLog:
    """Convert an ADK event stream into a structured `DeliberationLog`.

    Args:
        events: An iterable of ADK Event objects (or anything that
            duck-types similarly).
        company / industry_context / product_type: Scenario (the setting of a run) context
            recorded on the log for downstream analysis.

    Returns:
        A `DeliberationLog` whose `events` preserves order, author,
        addressee (where derivable), kind, text, and the underlying
        type name for debugging.
    """
    log = DeliberationLog(
        company=company,
        industry_context=industry_context,
        product_type=product_type,
    )
    for i, ev in enumerate(events):
        log.append(
            DeliberationEvent(
                index=i,
                role=_extract_role(ev),
                addressed_to=_extract_target(ev),
                kind=_classify(ev),
                text=_extract_text(ev),
                raw_type=type(ev).__name__,
            )
        )
    log.finished_at = datetime.utcnow().isoformat()
    return log
